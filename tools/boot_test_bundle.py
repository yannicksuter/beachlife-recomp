"""Move cross-built boot tests to a native runner, preserving CTest commands/properties."""
import argparse
import json
from pathlib import Path
import shutil
import subprocess
import sys

from package_build import inspect_package

ROOT = Path(__file__).resolve().parents[1]


def export(build, output, package):
    build, output = build.resolve(), output.resolve()
    tests = json.loads(subprocess.check_output(
        ['ctest', '--test-dir', str(build), '--show-only=json-v1'], text=True))['tests']
    if not tests or any(not test.get('command') for test in tests):
        raise ValueError('Build every test executable before exporting the CTest suite')
    output.mkdir(parents=True, exist_ok=True)
    _, files = inspect_package(package)
    for name, (body, mode) in files.items():
        destination = output / name
        destination.parent.mkdir(parents=True, exist_ok=True)
        destination.write_bytes(body)
        destination.chmod(mode)
    for executable in build.glob('*.exe'):
        shutil.copy2(executable, output / executable.name)
    (output/'generated').mkdir(exist_ok=True)
    shutil.copy2(build/'generated/build-info.json', output/'generated/build-info.json')
    (output/'tests.json').write_text(json.dumps({
        'source': str(ROOT), 'build': str(build), 'tests': tests}, indent=2)+'\n')


def relocate(value, old_source, old_build, source, build):
    if isinstance(value, list):
        return ';'.join(relocate(item, old_source, old_build, source, build) for item in value)
    value = str(value)
    for old, new in ((old_build, build), (old_source, source)):
        if value == old or value.startswith(old + '/'):
            return str(new).replace('\\', '/') + value[len(old):]
    return value


def quote(value):
    equals = '='
    while f']{equals}]' in value:
        equals += '='
    return f'[{equals}[{value}]{equals}]'


def configure(bundle):
    bundle = bundle.resolve()
    manifest = json.loads((bundle/'tests.json').read_text())
    def move(value):
        return relocate(value, manifest['source'], manifest['build'], ROOT, bundle)
    lines = ['# Relocated cross-build tests; generated by boot_test_bundle.py.']
    for test in manifest['tests']:
        command = list(test['command'])
        if Path(command[0]).name.startswith('python'):
            command[0] = sys.executable
        lines.append('add_test(' + ' '.join(quote(move(arg)) for arg in [test['name'], *command]) + ')')
        for prop in test['properties']:
            lines.append(f'set_tests_properties({quote(test["name"])} PROPERTIES '
                         f'{quote(prop["name"])} {quote(move(prop["value"]))})')
    (bundle/'CTestTestfile.cmake').write_text('\n'.join(lines)+'\n')
    print(f'Configured {len(manifest["tests"])} native boot tests in {bundle}')


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    commands = parser.add_subparsers(dest='command', required=True)
    stage = commands.add_parser('export')
    stage.add_argument('build', type=Path)
    stage.add_argument('output', type=Path)
    stage.add_argument('package', type=Path)
    native = commands.add_parser('configure')
    native.add_argument('bundle', type=Path)
    args = parser.parse_args()
    if args.command == 'export':
        export(args.build, args.output, args.package)
    else:
        configure(args.bundle)
